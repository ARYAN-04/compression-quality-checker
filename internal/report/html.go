// levelAccuracy computes accuracy over one compression level.
func levelAccuracy(results []domain.CellResult, lvl domain.CompressionLevel) float64 {
	n, ok := 0, 0
	for _, r := range results {
		if r.CompressionLevel != lvl {
			continue
		}
		n++
		if r.Correct() {
			ok++
		}
	}
	if n == 0 {
		return 0
	}
	return float64(ok) / float64(n)
}

// cliffOf wraps stats.DetectCliff for table building.
func cliffOf(levels []domain.CompressionLevel, scores map[domain.CompressionLevel]float64) (domain.CompressionLevel, float64, bool) {
	baseline := scores[domain.LevelNone]
	for _, l := range levels {
		if l == domain.LevelNone {
			continue
		}
		if baseline-scores[l] >= 0.10 {
			return l, baseline - scores[l], true
		}
	}
	return "", 0, false
}

// HTML renders a standalone responsive safety-matrix page with inline
// CSS bars per accuracy cell. No external assets or scripts required.
func (t SafetyTable) HTML(title string) string {
	var b strings.Builder
	b.WriteString(`<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>` + htmlpkg.EscapeString(title) + `</title>
<style>
:root{--bg:#0b1020;--card:#141c33;--line:#24304f;--text:#e8edf7;--muted:#93a0bd;--good:#4ade80;--warn:#fbbf24;--bad:#f87171;}
*{box-sizing:border-box;margin:0;padding:0;}
body{background:var(--bg);color:var(--text);font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;padding:2rem 1rem;line-height:1.5;}
.wrap{max-width:1100px;margin:0 auto;}
h1{font-size:1.6rem;margin-bottom:.3rem;}
.sub{color:var(--muted);margin-bottom:1.5rem;font-size:.9rem;}
.card{background:var(--card);border:1px solid var(--line);border-radius:12px;padding:1rem 1.25rem;margin-bottom:1.5rem;overflow-x:auto;}
table{border-collapse:collapse;width:100%;min-width:640px;}
th,td{padding:.55rem .75rem;text-align:left;border-bottom:1px solid var(--line);font-size:.9rem;}
th{color:var(--muted);font-weight:600;text-transform:uppercase;font-size:.72rem;letter-spacing:.06em;}
.bar{height:8px;border-radius:4px;background:var(--line);min-width:120px;position:relative;}
.bar span{position:absolute;inset:0;border-radius:4px;display:block;}
.good{background:var(--good);} .warn{background:var(--warn);} .bad{background:var(--bad);}
.cliff-none{color:var(--good);} .cliff-hit{color:var(--bad);font-weight:600;}
.pct{display:inline-block;width:52px;color:var(--muted);font-variant-numeric:tabular-nums;}
footer{color:var(--muted);font-size:.78rem;margin-top:1rem;}
@media(max-width:600px){body{padding:1rem .5rem;}h1{font-size:1.2rem;}}
</style>
</head>
<body><div class="wrap">
<h1>` + htmlpkg.EscapeString(title) + `</h1>
<p class="sub">Tool-use accuracy by model &times; schema compression level &middot; failure cliff = first level &ge;10pp below uncompressed baseline</p>
<div class="card"><table>
<tr><th>Model</th><th>Params (B)</th>`)
	for _, l := range t.Levels {
		fmt.Fprintf(&b, "<th>%s</th>", l)
	}
	b.WriteString("<th>Failure cliff</th></tr>")
	for _, row := range t.Rows {
		fmt.Fprintf(&b, "<tr><td>%s</td><td>%s</td>", row.Model, formatB(row.B))
		for _, l := range t.Levels {
			acc := row.Cells[l].Acc * 100
			class := "good"
			switch {
			case acc < 60:
				class = "bad"
			case acc < 85:
				class = "warn"
			}
			fmt.Fprintf(&b,
				`<td><span class="pct">%.1f%%</span><span class="bar"><span class="%s" style="width:%.0f%%"></span></span></td>`,
				acc, class, acc)
		}
		if row.HasCliff {
			fmt.Fprintf(&b, `<td class="cliff-hit">&ge; %s</td></tr>`, row.Cliff)
		} else {
			b.WriteString(`<td class="cliff-none">none observed</td></tr>`)
		}
	}
	b.WriteString(`</table></div>
<footer>Generated by can-i-compress-it</footer>
</div></body></html>
`)
	return b.String()
}

// SaveHTML writes the HTML report to path.
func SaveHTML(path, content string) error {
	return writeFileString(path, content)
}

// SaveMarkdown writes the markdown matrix to path.
func SaveMarkdown(path, md string) error {
	return writeFileString(path, md)
}
